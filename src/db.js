// Хранилище участников, сессий и записей.
//  • DATABASE_URL / POSTGRES_URL задан → Postgres (нужен на Vercel и других serverless-хостингах);
//  • иначе на обычном сервере → файл SQLite (встроенный node:sqlite);
//  • на Vercel без базы → db = null: рейтинги работают, вход и личные страницы отключены.
// Запросы пишутся с плейсхолдерами «?» и работают в обеих СУБД.
import fs from 'node:fs';
import path from 'node:path';
import pg from 'pg';
import { attachDatabasePool } from '@vercel/functions';
import { config } from './config.js';

const SCHEMA = `
  CREATE TABLE IF NOT EXISTS users (
    id               {id},
    username         TEXT    NOT NULL UNIQUE,          -- ник в нижнем регистре
    display_name     TEXT    NOT NULL,                 -- ник как на Chess.com
    name             TEXT,
    avatar           TEXT,
    country          TEXT,
    title            TEXT,
    league           TEXT,
    ratings          TEXT    NOT NULL DEFAULT '{}',    -- JSON: { "blitz": 1500, ... }
    tagline          TEXT    NOT NULL DEFAULT '',
    bio              TEXT    NOT NULL DEFAULT '',
    favorite_opening TEXT    NOT NULL DEFAULT '',
    goal_category    TEXT    NOT NULL DEFAULT 'blitz',
    goal_rating      INTEGER,
    accent           TEXT    NOT NULL DEFAULT '#81b64c',
    links            TEXT    NOT NULL DEFAULT '[]',
    auth_method      TEXT    NOT NULL,
    synced_at        {int8}  NOT NULL DEFAULT 0,
    created_at       {int8}  NOT NULL,
    updated_at       {int8}  NOT NULL
  );

  CREATE TABLE IF NOT EXISTS sessions (
    token      TEXT   PRIMARY KEY,                     -- sha256 от значения cookie
    user_id    {int8} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires_at {int8} NOT NULL
  );

  CREATE TABLE IF NOT EXISTS posts (
    id         {id},
    user_id    {int8} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    body       TEXT   NOT NULL,
    created_at {int8} NOT NULL
  );
  CREATE INDEX IF NOT EXISTS posts_by_user ON posts(user_id, created_at DESC);

  -- незавершённые входы: OAuth state + PKCE verifier или код подтверждения профиля
  CREATE TABLE IF NOT EXISTS pending_auth (
    id         TEXT   PRIMARY KEY,
    kind       TEXT   NOT NULL,
    username   TEXT,
    secret     TEXT   NOT NULL,
    expires_at {int8} NOT NULL
  );
`;

const TYPES = {
  sqlite: { id: 'INTEGER PRIMARY KEY AUTOINCREMENT', int8: 'INTEGER' },
  postgres: { id: 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', int8: 'BIGINT' },
};
const schemaFor = (kind) => SCHEMA.replace(/\{(id|int8)\}/g, (_, type) => TYPES[kind][type]);

function createPostgres() {
  pg.types.setTypeParser(20, Number); // BIGINT (миллисекунды, id, COUNT) → number
  const pool = new pg.Pool({ connectionString: config.databaseUrl, max: 5, idleTimeoutMillis: 10_000 });
  pool.on('error', (err) => console.warn('Postgres:', err.message)); // обрыв простаивающего соединения не должен ронять процесс
  if (config.isVercel) attachDatabasePool(pool);

  let ready = null;
  const init = () => (ready ||= pool.query(schemaFor('postgres')).catch((err) => {
    ready = null;
    throw err;
  }));
  const toPg = (sql) => {
    let n = 0;
    return sql.replace(/\?/g, () => `$${++n}`);
  };
  const query = async (sql, params) => {
    await init();
    return pool.query(toPg(sql), params);
  };

  return {
    kind: 'postgres',
    get: async (sql, params = []) => (await query(sql, params)).rows[0] ?? null,
    all: async (sql, params = []) => (await query(sql, params)).rows,
    run: async (sql, params = []) => ({ changes: (await query(sql, params)).rowCount }),
  };
}

async function createSqlite() {
  const { DatabaseSync } = await import('node:sqlite');
  fs.mkdirSync(path.dirname(config.dbPath), { recursive: true });
  const sqlite = new DatabaseSync(config.dbPath);
  sqlite.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;');
  sqlite.exec(schemaFor('sqlite'));

  return {
    kind: 'sqlite',
    get: async (sql, params = []) => sqlite.prepare(sql).get(...params) ?? null,
    all: async (sql, params = []) => sqlite.prepare(sql).all(...params),
    run: async (sql, params = []) => ({ changes: Number(sqlite.prepare(sql).run(...params).changes) }),
  };
}

export const db = config.databaseUrl ? createPostgres() : config.isVercel ? null : await createSqlite();
export const dbEnabled = db !== null;

if (!db) console.warn('База данных не подключена: вход и личные страницы отключены. Задайте DATABASE_URL.');

async function cleanupExpired() {
  if (!db) return;
  const now = Date.now();
  await db.run('DELETE FROM sessions WHERE expires_at < ?', [now]);
  await db.run('DELETE FROM pending_auth WHERE expires_at < ?', [now]);
}
cleanupExpired().catch((err) => console.warn('Очистка устаревших сессий:', err.message));
setInterval(() => cleanupExpired().catch(() => {}), 60 * 60_000).unref();
